class GenModel(nn.Module):
    def __init__(self, config):
        super().__init__()
        self.config = config
        self.token_emb = nn.Embedding(config.vocab_size, config.dim)

        self.layers = nn.ModuleList()

        for _ in range(config.n_layers):
            # We always use Surgical classes; they adapt based on the Config
            self.layers.append(nn.ModuleDict({
                'norm1': RMSNorm(config.dim),
                'attn': SurgicalAttention(config),
                'norm2': RMSNorm(config.dim),
                'mlp': SurgicalMLP(config)
            }))

        self.norm = RMSNorm(config.dim)
        self.lm_head = nn.Linear(config.dim, config.vocab_size, bias=False)
        self.token_emb.weight = self.lm_head.weight

    def forward(self, idx, targets=None, step=None):
        B, L = idx.shape
        x = self.token_emb(idx)

        total_aux_loss = 0.0

        # 2. Transformer Blocks
        for layer in self.layers:
            # Attn
            norm_x = layer['norm1'](x)
            attn_out, attn_loss = layer['attn'](norm_x)
            x = x + attn_out
            total_aux_loss += attn_loss

            # MLP
            norm_x = layer['norm2'](x)
            mlp_out, mlp_loss = layer['mlp'](norm_x)
            x = x + mlp_out
            total_aux_loss += mlp_loss

        x = self.norm(x)
        logits = self.lm_head(x)

        final_loss = None
        if targets is not None:
            # Calculate Cross Entropy
            ce_loss = F.cross_entropy(logits.view(-1, logits.size(-1)), targets.view(-1))
            final_loss = ce_loss + total_aux_loss

        return logits, final_loss

