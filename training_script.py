class InfiniteTextDataset(IterableDataset):
    def __init__(self, seq_len, skip_tokens=0):
        self.seq_len = seq_len
        self.tokenizer = AutoTokenizer.from_pretrained("HuggingFaceTB/SmolLM2-135M")
        self.dataset = load_dataset("HuggingFaceFW/fineweb-edu", name="default", split="train", streaming=True)
        if skip_tokens == 0:
            self.dataset = self.dataset.take(10_000)
        else:
            self.dataset = self.dataset.skip(skip_tokens)
            self.dataset = self.dataset.shuffle(seed=42, buffer_size=10_000)

    def __iter__(self):
        buffer = []
        for sample in self.dataset:
            tokens = self.tokenizer.encode(sample['text'], add_special_tokens=False, truncation=True, max_length=8192)
            tokens.append(self.tokenizer.eos_token_id)
            buffer.extend(tokens)
            while len(buffer) >= self.seq_len + 1:
                chunk = buffer[:self.seq_len + 1]
                buffer = buffer[self.seq_len + 1:]
                yield {
                    "input_ids": torch.tensor(chunk[:-1], dtype=torch.long),
                    "labels": torch.tensor(chunk[1:], dtype=torch.long)
                }


