class StandardLinearWrapper(nn.Module):
    """
    Wraps a standard nn.Linear to match the signature of HybridDualPathLinear.
    Returns: (output, 0.0)
    """
    def __init__(self, in_features, out_features, bias=False, **kwargs):
        super().__init__()
        self.linear = nn.Linear(in_features, out_features, bias=bias)

    def forward(self, x):
        return self.linear(x), 0.0

class HybridDualPathLinear(nn.Module):
    """
    Topology-Corrected Projection.
    Path 1: Block-Diagonal (Full Rank, Local)
    Path 2: Variational (Low Rank, Global)
    """
    def __init__(self, in_features, out_features, latent_dim, beta=0.01, num_blocks=4, **kwargs):
        super().__init__()
        self.in_features = in_features
        self.out_features = out_features
        self.beta = beta

        # --- PATH 1: The "Detail" Path (Block-Diagonal) ---
        self.groups = num_blocks
        if in_features % self.groups != 0 or out_features % self.groups != 0:
            self.groups = 1

        self.block_path = nn.Conv1d(
            in_channels=in_features,
            out_channels=out_features,
            kernel_size=1,
            groups=self.groups,
            bias=False
        )

        # --- PATH 2: The "Context" Path (Global VAE) ---
        self.vae_rank = latent_dim
        self.enc_mu = nn.Linear(in_features, latent_dim)
        self.enc_logvar = nn.Linear(in_features, latent_dim)
        self.decoder = nn.Linear(latent_dim, out_features, bias=False)

        # --- Initialization ---
        if self.in_features == self.out_features:
            nn.init.dirac_(self.block_path.weight)
            with torch.no_grad():
                self.block_path.weight.add_(torch.randn_like(self.block_path.weight) * 0.01)
        else:
            nn.init.orthogonal_(self.block_path.weight)

        nn.init.orthogonal_(self.enc_mu.weight)
        nn.init.zeros_(self.enc_logvar.weight)
        nn.init.orthogonal_(self.decoder.weight)

    def forward(self, x):
        # x: [Batch, Len, Dim]

        # --- Path 1: Block Diagonal ---
        x_perm = x.transpose(1, 2)
        detail_out = self.block_path(x_perm)
        detail_out = detail_out.transpose(1, 2)

        # --- Path 2: VAE ---
        mu = self.enc_mu(x)
        logvar = self.enc_logvar(x)

        if self.training:
            std = torch.exp(0.5 * logvar)
            eps = torch.randn_like(std)
            z = mu + eps * std
            loss = geometric_jsd_loss(mu, logvar) * self.beta
        else:
            z = mu
            loss = 0.0

        context_out = self.decoder(F.silu(z))

        out = detail_out + context_out
        return out, loss

def build_linear(in_dim, out_dim, is_hybrid, config):
    """Factory function to choose between Standard and Hybrid layers."""
    if is_hybrid:
        return HybridDualPathLinear(
            in_dim,
            out_dim,
            latent_dim=config.vae_linear_rank,
            beta=config.vae_beta,
            num_blocks=8 # Default block count
        )
    else:
        return StandardLinearWrapper(in_dim, out_dim, bias=False)

