class LlamaRotaryEmbedding(nn.Module):
    def __init__(self, dim, max_position_embeddings=32768, base=500000.0):
        super().__init__()
        inv_freq = 1.0 / (base ** (torch.arange(0, dim, 2).float() / dim))
        self.register_buffer("inv_freq", inv_freq, persistent=False)
        self.max_seq_len_cached = max_position_embeddings
        t = torch.arange(self.max_seq_len_cached, dtype=torch.float32)
        freqs = torch.outer(t, self.inv_freq)
        emb = torch.cat((freqs, freqs), dim=-1)
        self.register_buffer("cos_cached", emb.cos(), persistent=False)
        self.register_buffer("sin_cached", emb.sin(), persistent=False)

    def forward(self, x, seq_len):
        if seq_len > self.max_seq_len_cached:
            self.__init__(x.shape[-1], max_position_embeddings=seq_len*2)
            self.to(x.device)
        return self.cos_cached[:seq_len, ...].to(x.dtype), self.sin_cached[:seq_len, ...].to(x.dtype)

def apply_rotary_pos_emb(q, k, cos, sin):
    def rotate_half(x): return torch.cat((-x[..., x.shape[-1]//2:], x[..., :x.shape[-1]//2]), dim=-1)
    cos, sin = cos[None, None, :, :], sin[None, None, :, :]
    return (q * cos) + (rotate_half(q) * sin), (k * cos) + (rotate_half(k) * sin)


class SurgicalAttention(nn.Module):
    def __init__(self, config):
        super().__init__()
        self.n_heads = config.n_heads
        self.head_dim = config.head_dim
        dim = config.dim
        out_dim = config.n_heads * config.head_dim

        # Surgically instantiate based on Config flags
        self.q_proj = build_linear(dim, out_dim, config.hybrid_q, config)
        self.k_proj = build_linear(dim, out_dim, config.hybrid_k, config)
        self.v_proj = build_linear(dim, out_dim, config.hybrid_v, config)
        self.o_proj = build_linear(out_dim, dim, config.hybrid_o, config)

        self.rotary = LlamaRotaryEmbedding(config.head_dim)

    def forward(self, x):
        B, L, _ = x.shape

        # 1. Project Q, K, V (returns value, loss)
        q_flat, q_loss = self.q_proj(x)
        k_flat, k_loss = self.k_proj(x)
        v_flat, v_loss = self.v_proj(x)

        q = q_flat.view(B, L, self.n_heads, self.head_dim).transpose(1, 2)
        k = k_flat.view(B, L, self.n_heads, self.head_dim).transpose(1, 2)
        v = v_flat.view(B, L, self.n_heads, self.head_dim).transpose(1, 2)

        cos, sin = self.rotary(v, L)
        q, k = apply_rotary_pos_emb(q, k, cos, sin)

        attn_out = F.scaled_dot_product_attention(q, k, v, is_causal=True)
        attn_out = attn_out.transpose(1, 2).contiguous().view(B, L, -1)

        final_out, o_loss = self.o_proj(attn_out)

        total_aux_loss = q_loss + k_loss + v_loss + o_loss
        return final_out, total_aux_loss

class SurgicalMLP(nn.Module):
    def __init__(self, config):
        super().__init__()
        # Surgically instantiate based on Config flags
        self.gate_proj = build_linear(config.dim, config.hidden_dim, config.hybrid_gate, config)
        self.up_proj   = build_linear(config.dim, config.hidden_dim, config.hybrid_up,   config)
        self.down_proj = build_linear(config.hidden_dim, config.dim, config.hybrid_down, config)

    def forward(self, x):
        gate_out, gate_loss = self.gate_proj(x)
        gate_out = F.silu(gate_out)

        up_out, up_loss = self.up_proj(x)

        intermediate = gate_out * up_out

        down_out, down_loss = self.down_proj(intermediate)

        return down_out, gate_loss + up_loss + down_loss

