    val_loader = DataLoader(val_ds, batch_size=Config.batch_size, num_workers=0, drop_last=True)

    all_results = {}

    for run_name in run_configs:
        xm.master_print(f"\n\n>>> STARTING TRAINING: {run_name.upper()} on TPU")

        # --- CONFIGURE LAYERS SURGICALLY ---
        if run_name == "Baseline":
            # FORCE ALL STANDARD
            Config.hybrid_q = False
            Config.hybrid_k = False
            Config.hybrid_v = False
            Config.hybrid_o = False
            Config.hybrid_gate = False
            Config.hybrid_up = False
            Config.hybrid_down = False

        # elif run_name == "Surgical_Method":
        #     # --- USER CONFIGURATION ZONE ---
        #     Uncomment lines below to enable hybrid on other components

        #     Config.hybrid_q = False     # Set True to make Wq hybrid
        #     Config.hybrid_k = False     # Set True to make Wk hybrid
        #     Config.hybrid_v = False     # Set True to make Wv hybrid
        #     Config.hybrid_o = True      # <--- ACTIVE (Default)

        #     Config.hybrid_gate = False  # Set True to make Gate hybrid
        #     Config.hybrid_up = False    # Set True to make Up hybrid
        #     Config.hybrid_down = True   # <--- ACTIVE (Default)
        #     # -------------------------------

        # Instantiate Model with current flags
        model = GenModel(Config).to(device)
        mb_size, param_count = get_model_infos(model)
        xm.master_print(f"Model: {run_name} | Size: {mb_size:.2f} MB | Params: {param_count:,}")

        # Log active hybrid layers
        if xm.is_master_ordinal():
            print(f"  > Hybrid Layers Active:")
            print(f"    Attn: Q={Config.hybrid_q}, K={Config.hybrid_k}, V={Config.hybrid_v}, O={Config.hybrid_o}")
            print(f"    MLP:  Gate={Config.hybrid_gate}, Up={Config.hybrid_up}, Down={Config.hybrid_down}")

        param_dict = {pn: p for pn, p in model.named_parameters() if p.requires_grad}
        decay_params = [p for n, p in param_dict.items() if p.dim() >= 2]
        nodecay_params = [p for n, p in param_dict.items() if p.dim() < 2]

        optim_groups = [
            {'params': decay_params, 'weight_decay': Config.weight_decay},
            {'params': nodecay_params, 'weight_decay': 0.0}
        ]
        optimizer = torch.optim.AdamW(optim_groups, lr=Config.learning_rate, betas=(0.9, 0.95))
        scheduler = get_cosine_schedule_with_warmup(
            optimizer,
            num_warmup_steps=Config.warmup_steps,
            num_training_steps=Config.max_steps
        )

        model.train()

        start_time = time.time()
        model_start_time = time.time()

        best_val_loss = float('inf')
        train_history = []
        val_history = []
        step_history = []
        current_ce_losses = []
        current_aux_losses = []

        try:
            for step in range(Config.max_steps):
                elapsed_global = time.time() - global_start
                elapsed_model = time.time() - model_start_time
                if elapsed_global > (time_limit_sec - 600):
                    xm.master_print("!!! GLOBAL TIME LIMIT APPROACHING. STOPPING. !!!")
                    break
                if elapsed_model > budget_per_model:
                    xm.master_print(f"!!! TIME LIMIT FOR {run_name} REACHED. !!!")
                    break

                try:
                    batch = next(train_iterator)
                except StopIteration:
                    xm.master_print("Iterator exhausted. Restarting...")
                    train_iterator = iter(para_train_loader)
                    batch = next(train_iterator)

                input_ids = batch['input_ids']
                labels = batch['labels']

                optimizer.zero_grad()
                logits, total_loss = model(input_ids, labels, step=step)

                with torch.no_grad():
                    ce_val = F.cross_entropy(logits.view(-1, logits.size(-1)), labels.view(-1)).item()
                    aux_val = total_loss.item() - ce_val
                    current_ce_losses.append(ce_val)
                    current_aux_losses.append(aux_val)

                total_loss.backward()

                if Config.use_grad_clip:
                    xm.reduce_gradients(optimizer)
                    torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                    optimizer.step()
                else:
                    xm.optimizer_step(optimizer)

                scheduler.step()

                if step > 0 and step % Config.eval_interval == 0:
                    avg_ce = sum(current_ce_losses) / len(current_ce_losses)
                    avg_aux = sum(current_aux_losses) / len(current_aux_losses)
                    current_ce_losses = []
                    current_aux_losses = []

                    model.eval()
                    val_loss_accum = 0.0
                    val_count = 0

                    with torch.no_grad():
                        for i, val_batch in enumerate(val_loader):
                            if i >= Config.val_steps: break
                            v_input = val_batch['input_ids'].to(device)
                            v_labels = val_batch['labels'].to(device)
                            _, v_loss = model(v_input, v_labels)
                            val_loss_accum += v_loss.item()
                            val_count += 1

                    avg_val_loss = val_loss_accum / val_count if val_count > 0 else 0.0

                    if avg_val_loss < best_val_loss:
                        best_val_loss = avg_val_loss
                        xm.master_print(f"--> New Best Val Loss: {best_val_loss:.4f}. Saving Model...")
                        xm.save(model.state_dict(), f"{Config.output_dir}/best_model_{run_name}.pt")

                    train_history.append(avg_ce + avg_aux)
                    val_history.append(avg_val_loss)
                    step_history.append(step)

                    dt = time.time() - start_time
                    tok_sec = (Config.batch_size * Config.seq_len * 8 * Config.eval_interval) / dt

                    xm.master_print(
                        f"[{run_name}] Step {step} | "
                        f"CE: {avg_ce:.4f} | "
                        f"Aux: {avg_aux:.4f} | "
                        f"Val: {avg_val_loss:.4f} | "
                        f"Speed: {tok_sec:.0f} tok/s"
                    )

                    model.train()
                    start_time = time.time()

        except Exception as e:
            xm.master_print(f"ERR: Training loop crashed for {run_name}: {e}")
            import traceback
            traceback.print_exc()

        if xm.is_master_ordinal():
            try:
                plt.figure(figsize=(10, 6))
                plt.plot(step_history, train_history, label='Train Loss', alpha=0.7)
                plt.plot(step_history, val_history, label='Val Loss', linewidth=2)
                plt.title(f'{run_name} Training Curve')
                plt.xlabel('Steps')
                plt.ylabel('Loss')
                plt.legend()
                plt.grid(True, alpha=0.3)
                plt.savefig(f"{Config.output_dir}/plot_{run_name}.png")
                plt.close()
            except Exception as e:
                print(f"Plotting failed: {e}")

        all_results[run_name] = {
            "steps": step_history,
            "train": train_history,
            "val": val_history
        }

        del model
        del optimizer
        xm.mark_step()
        gc.collect()

    if xm.is_master_ordinal():
        try:
            plt.figure(figsize=(12, 8))
            colors = plt.cm.tab20(np.linspace(0, 1, len(all_results)))

            for i, (mode_name, data) in enumerate(all_results.items()):
                plt.plot(
                    data["steps"],
                    data["val"],
                    label=f'{mode_name} (Val)',
                    color=colors[i],
                    linewidth=2
                )

            plt.title('Comparison: Baseline vs Surgical Hybrid')
            plt.xlabel('Steps')
            plt.ylabel('Loss')
            plt.legend(bbox_to_anchor=(1.05, 1), loc='upper left')
            plt.grid(True, alpha=0.3)
            plt.tight_layout()
            plt.savefig(f"{Config.output_dir}/final_comparison.png")
            plt.close()
        except Exception as e:
            print(f"Final plotting failed: {e}")


